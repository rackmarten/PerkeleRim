    pieces.Add(Place(Base(skyrim.Statics, piece), shackTiles[tile], shackY, shackGround.Low - wallSink, rot));
pieces.Add(Place(Base(skyrim.Furniture, "CommonBed01"), bedSpot.X, bedSpot.Y, GroundAt(bedSpot.X, bedSpot.Y), 0f));
