// ---- Cells ----
//
// Overriding a record through its context copies only that cell (and the empty worldspace, block and
// sub-block records above it) into the plugin, not the whole of Tamriel.
var cellContexts = skyrim.EnumerateMajorRecordContexts<ICell, ICellGetter>(cache).ToList();

ICell Override(ICellGetter cell) =>
    cellContexts.First(c => c.Record.FormKey == cell.FormKey).GetOrAddAsOverride(mod);

ICellGetter ExteriorAt(float x, float y)
{
    int cx = (int)MathF.Floor(x / 4096f), cy = (int)MathF.Floor(y / 4096f);
    return tamriel.SubCells.SelectMany(b => b.Items).SelectMany(s => s.Items)
        .First(c => c.Grid != null && c.Grid.Point.X == cx && c.Grid.Point.Y == cy);
}

var persistentCell = Override(tamriel.TopCell ?? throw new InvalidOperationException("Tamriel has no persistent cell"));
foreach (var m in markers) persistentCell.Persistent.Add(m);
foreach (var p in pieces)
{
    var cell = Override(ExteriorAt(p.Placement!.Position.X, p.Placement.Position.Y));
    cell.Temporary.Add(p);
}

foreach (var p in markers.Concat(pieces))
{
    var at = p.Placement!;
    var name = cache.Resolve<IPlaceableObjectGetter>(p.Base.FormKey).EditorID;
    Console.WriteLine($"  {p.FormKey.ID:X3} {name,-16} ({at.Position.X:0},{at.Position.Y:0},{at.Position.Z:0}) rot {at.Rotation.Z:0.000}");
}

