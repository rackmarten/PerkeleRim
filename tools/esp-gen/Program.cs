// Writes PerkeleRim.esp: the garage near Whiterun (vanilla pieces) with the player's spawn marker in
// front of it and a marker where the van parks inside, the mead and ale that become MSC beer, the
// drunk blur and the pocket's items (MSC's beer, bottles, food and cigarettes). Reads only the
// player's own Skyrim.esm (for the vanilla base objects, the Tamriel cells to add to and the terrain
// height there). Also the spells MSC's punch lands as.
//
//   EspGen --data "<Skyrim>/Data" --out <dir>/PerkeleRim.esp
//
// The output depends only on Skyrim.esm and this file, so it rebuilds byte for byte.

using Mutagen.Bethesda;
using Mutagen.Bethesda.Plugins;
using Mutagen.Bethesda.Plugins.Cache;
using Mutagen.Bethesda.Plugins.Records;
using Mutagen.Bethesda.Skyrim;
using Noggog;
using PerkeleRim.EspGen;

string? data = null, output = null;
for (int i = 0; i + 1 < args.Length; i += 2)
{
    if (args[i] == "--data") data = args[i + 1];
    else if (args[i] == "--out") output = args[i + 1];
}
if (data == null || output == null)
{
    Console.Error.WriteLine("usage: EspGen --data <Skyrim Data folder> --out <PerkeleRim.esp>");
    return 2;
}

using var skyrim = SkyrimMod.CreateFromBinaryOverlay(Path.Combine(data, "Skyrim.esm"), SkyrimRelease.SkyrimSE);
var cache = skyrim.ToImmutableLinkCache();
var tamriel = skyrim.Worldspaces.First(w => w.EditorID == "Tamriel");
var terrain = new Terrain(tamriel);

var mod = new SkyrimMod(ModKey.FromFileName(Path.GetFileName(output)), SkyrimRelease.SkyrimSE);
mod.ModHeader.Author = "PerkeleRim";
mod.ModHeader.Description = "The PerkeleRim garage near Whiterun. Generated by tools/esp-gen, do not edit.";

// ---- Layout ----
//
// Garage frame: origin at the shed's middle, +X out of the open front, Z up. Rotation is Skyrim's:
// clockwise seen from above, radians. Units are Skyrim units (1 m = 70 units).

// On the flat tundra south-west of the Whiterun stables, off the road. Picked in game: center where
// the van parks, front the way it drives out. docs/DESIGN.md has the history.
var center = (X: 15170f, Y: -14516f);
// The front faces 31.7 degrees east of north (picked in game with player.getangle z); local +X
// is heading 90 degrees at yaw 0.
const float yaw = (31.7f - 90f) * MathF.PI / 180f;

// SFarmShed01: a 720 x 496 open pole shed whose posts reach 160 below its origin. Raised a little
// above the highest ground under it so the van (about 150 tall) clears the beams.
const float shedRaise = 10f;
// ShackKit walls: 256 long (X), 192 tall from their origin, standing on the +Y edge (y 119..136)
// of the 256 square around it. Sunk a little below the lowest ground so they never float.
const float wallSink = 10f;
var walls = new (string Wall, float X, float Y, float Rot)[]
{
    // back (-X end), facing in
    ("ShackWall01", -222f, -128f, -MathF.PI / 2),
    ("ShackWall02", -222f, 128f, -MathF.PI / 2),
    // left side (+Y), the middle piece set out 2 so overlapping planks don't flicker
    ("ShackWall05", -224f, 104f, 0f),
    ("ShackWall01", 32f, 106f, 0f),
    ("ShackWall02", 248f, 104f, 0f),
    // right side (-Y)
    ("ShackWall02", -224f, -104f, MathF.PI),
    ("ShackWall05", 32f, -106f, MathF.PI),
    ("ShackWall01", 248f, -104f, MathF.PI),
};
var footprint = (HalfX: 380f, HalfY: 260f);
var vanSpot = (X: 0f, Y: 0f);     // the van's middle, nose out of the front
var spawnSpot = (X: 620f, Y: 0f);  // in front of the opening, looking in

// ---- Placement helpers ----

(float X, float Y) World(float x, float y)
{
    float c = MathF.Cos(yaw), s = MathF.Sin(yaw);
    return (center.X + x * c + y * s, center.Y - x * s + y * c);
}

// Heading (clockwise from north) of the garage's local direction (dx, dy).
float Heading(float dx, float dy) => Normalize(MathF.Atan2(dx, dy) + yaw);
static float Normalize(float a) => ((a % MathF.Tau) + MathF.Tau) % MathF.Tau;

float groundLow = float.MaxValue, groundHigh = float.MinValue;
for (float x = -footprint.HalfX; x <= footprint.HalfX; x += 32f)
for (float y = -footprint.HalfY; y <= footprint.HalfY; y += 32f)
{
    var w = World(x, y);
    float h = terrain.HeightAt(w.X, w.Y);
    groundLow = Math.Min(groundLow, h);
    groundHigh = Math.Max(groundHigh, h);
}
Console.WriteLine($"ground under the garage: {groundLow:0} .. {groundHigh:0}");

FormKey Base<T>(IEnumerable<T> records, string editorId) where T : IMajorRecordGetter =>
    records.FirstOrDefault(r => r.EditorID == editorId)?.FormKey ?? throw new InvalidOperationException($"{editorId} not in Skyrim.esm");
var marker = new FormKey(skyrim.ModKey, 0x000034);  // XMarkerHeading

uint nextId = 0x800;
PlacedObject Place(FormKey baseObject, float x, float y, float z, float rot, bool persistent = false)
{
    var w = World(x, y);
    var placed = new PlacedObject(new FormKey(mod.ModKey, nextId++), SkyrimRelease.SkyrimSE)
    {
        Base = new FormLinkNullable<IPlaceableObjectGetter>(baseObject),
        Placement = new Placement { Position = new P3Float(w.X, w.Y, z), Rotation = new P3Float(0f, 0f, Normalize(rot + yaw)) },
    };
    if (persistent) placed.MajorRecordFlagsRaw |= (int)PlacedObject.StaticMajorFlag.Persistent;
    return placed;
}

// Markers first, at the fixed ids the SKSE plugin looks up (skse/src/garage/Garage.cpp). Persistent,
// so they exist while their cell isn't loaded: the plugin moves the player to the spawn marker.
var spawnWorld = World(spawnSpot.X, spawnSpot.Y);
var vanWorld = World(vanSpot.X, vanSpot.Y);
var markers = new List<PlacedObject>
{
    Place(marker, spawnSpot.X, spawnSpot.Y, terrain.HeightAt(spawnWorld.X, spawnWorld.Y), Heading(-1f, 0f) - yaw, persistent: true),  // 0x800
    Place(marker, vanSpot.X, vanSpot.Y, terrain.HeightAt(vanWorld.X, vanWorld.Y), Heading(1f, 0f) - yaw, persistent: true),        // 0x801
};
markers[0].EditorID = "PerkeleRimGarageSpawnMarker";
markers[1].EditorID = "PerkeleRimGarageVanMarker";

var pieces = new List<PlacedObject> { Place(Base(skyrim.Statics, "SFarmShed01"), 0f, 0f, groundHigh + shedRaise, 0f) };
foreach (var (wall, x, y, rot) in walls)
    pieces.Add(Place(Base(skyrim.Statics, wall), x, y, groundLow - wallSink, rot));
mod.ModHeader.Stats.NextFormID = nextId;

// ---- Cells ----
//
// Overriding a record through its context copies only that cell (and the empty worldspace, block and
// sub-block records above it) into the plugin, not the whole of Tamriel.
var cellContexts = skyrim.EnumerateMajorRecordContexts<ICell, ICellGetter>(cache).ToList();

ICell Override(ICellGetter cell) =>
    cellContexts.First(c => c.Record.FormKey == cell.FormKey).GetOrAddAsOverride(mod);

ICellGetter ExteriorAt(float x, float y)
{
    int cx = (int)MathF.Floor(x / 4096f), cy = (int)MathF.Floor(y / 4096f);
    return tamriel.SubCells.SelectMany(b => b.Items).SelectMany(s => s.Items)
        .First(c => c.Grid != null && c.Grid.Point.X == cx && c.Grid.Point.Y == cy);
}

var persistentCell = Override(tamriel.TopCell ?? throw new InvalidOperationException("Tamriel has no persistent cell"));
foreach (var m in markers) persistentCell.Persistent.Add(m);
foreach (var p in pieces)
{
    var cell = Override(ExteriorAt(p.Placement!.Position.X, p.Placement.Position.Y));
    cell.Temporary.Add(p);
}

foreach (var p in markers.Concat(pieces))
{
    var at = p.Placement!;
    var name = cache.Resolve<IPlaceableObjectGetter>(p.Base.FormKey).EditorID;
    Console.WriteLine($"  {p.FormKey.ID:X3} {name,-16} ({at.Position.X:0},{at.Position.Y:0},{at.Position.Z:0}) rot {at.Rotation.Z:0.000}");
}

// ---- Drinks ----
//
// Fixed ids the SKSE plugin looks up (skse/src/drink/Drink.cpp, skse/src/pocket/Pocket.cpp), clear of
// the garage's.
//
// The mead and ale that turn into MSC beer (the pocket's PerkeleRimBeer) when the player picks them up. Quest drinks
// (MQ101JuniperMead, FreeformDragonBridgeMead) stay out: taking them away would break their quests.
var drinks = new FormList(new FormKey(mod.ModKey, 0x900), SkyrimRelease.SkyrimSE) { EditorID = "PerkeleRimBeerDrinks" };
foreach (var id in new[] { "FoodMead", "Ale", "FoodHonningbrewMead", "FoodBlackBriarMead", "FoodBlackBriarMeadPrivateReserve" })
    drinks.Items.Add(new FormLink<ISkyrimMajorRecordGetter>(Base(skyrim.Ingestibles, id)));
mod.FormLists.Add(drinks);

// MSC's drunk level as a blur with wobbling double vision. A 4 s loop the plugin retriggers, its
// strength the drunk level; copied from a vanilla static blur so every other track stays neutral.
var vanillaBlur = skyrim.ImageSpaceAdapters.First(a => a.EditorID == "ISMDinCloudBlurStatic");
var drunk = (ImageSpaceAdapter)vanillaBlur.Duplicate(new FormKey(mod.ModKey, 0x901));
drunk.EditorID = "PerkeleRimDrunkIMAD";
drunk.Duration = 4f;
drunk.Animatable = true;
ExtendedList<KeyFrame> Track(params (float Time, float Value)[] keys) =>
    new(keys.Select(k => new KeyFrame { Time = k.Time, Value = k.Value }));
drunk.BlurRadius = Track((0f, 2f), (0.5f, 3.5f), (1f, 2f));
drunk.DoubleVisionStrength = Track((0f, 0.01f), (0.25f, 0.025f), (0.5f, 0.008f), (0.75f, 0.022f), (1f, 0.01f));
var clear = System.Drawing.Color.FromArgb(0, 255, 255, 255);
drunk.FadeColor = new ExtendedList<ColorFrame> { new ColorFrame { Time = 0f, Color = clear }, new ColorFrame { Time = 1f, Color = clear } };
mod.ImageSpaceAdapters.Add(drunk);
Console.WriteLine($"  900 {drinks.EditorID} ({drinks.Items.Count} drinks)");
Console.WriteLine($"  901 {drunk.EditorID}");

// ---- Combat ----
//
// Fixed ids the SKSE plugin looks up (skse/src/combat/Combat.cpp). MSC's punch lands on an actor as
// two hostile spells the plugin casts from the player at it: the damage (magnitude set per cast, a
// share of the target's max health) and a stagger. Being the player's hostile spells, the target
// fights back and a hit on someone peaceful is assault, the way Skyrim treats any attack.
MagicEffect Effect(uint id, string editorId, string name, MagicEffectArchetype archetype)
{
    var effect = new MagicEffect(new FormKey(mod.ModKey, id), SkyrimRelease.SkyrimSE)
    {
        EditorID = editorId,
        Name = name,
        Flags = MagicEffect.Flag.Hostile | MagicEffect.Flag.Detrimental | MagicEffect.Flag.NoDuration | MagicEffect.Flag.NoArea,
        Archetype = archetype,
        CastType = CastType.FireAndForget,
        TargetType = TargetType.TargetActor,
        MagicSkill = ActorValue.None,
        ResistValue = ActorValue.None,
    };
    mod.MagicEffects.Add(effect);
    return effect;
}
Spell Spell(uint id, string editorId, string name, MagicEffect effect, float magnitude)
{
    var spell = new Spell(new FormKey(mod.ModKey, id), SkyrimRelease.SkyrimSE)
    {
        EditorID = editorId,
        Name = name,
        Type = SpellType.Spell,
        CastType = CastType.FireAndForget,
        TargetType = TargetType.TargetActor,
        Flags = SpellDataFlag.ManualCostCalc | SpellDataFlag.NoAbsorbOrReflect,
        BaseCost = 0,
    };
    spell.Effects.Add(new Effect { BaseEffect = effect.ToNullableLink(), Data = new EffectData { Magnitude = magnitude } });
    mod.Spells.Add(spell);
    return spell;
}
var punchDamage = Effect(0x902, "PerkeleRimPunchDamageEffect", "Punch",
    new MagicEffectArchetype(MagicEffectArchetype.TypeEnum.ValueModifier) { ActorValue = ActorValue.Health });
var punchStagger = Effect(0x903, "PerkeleRimPunchStaggerEffect", "Punch",
    new MagicEffectArchetype(MagicEffectArchetype.TypeEnum.Stagger));
var punch = Spell(0x904, "PerkeleRimPunch", "Punch", punchDamage, 1f);
var punchKnock = Spell(0x905, "PerkeleRimPunchStagger", "Punch", punchStagger, 0.5f);
foreach (var r in new IMajorRecordGetter[] { punchDamage, punchStagger, punch, punchKnock })
    Console.WriteLine($"  {r.FormKey.ID:X3} {r.EditorID}");
// Thrown items land as the punch spells too. Piss is poison: damage health per second (magnitude set
// per cast, protocol/cpp/damage.h) for kPissSeconds, resisted by poison resistance. Recasting while the
// stream stays on refreshes it.
var pissPoison = Effect(0x90D, "PerkeleRimPissEffect", "Piss",
    new MagicEffectArchetype(MagicEffectArchetype.TypeEnum.ValueModifier) { ActorValue = ActorValue.Health });
pissPoison.Flags = MagicEffect.Flag.Hostile | MagicEffect.Flag.Detrimental | MagicEffect.Flag.NoArea;
pissPoison.ResistValue = ActorValue.PoisonResist;
var piss = Spell(0x90E, "PerkeleRimPiss", "Piss", pissPoison, 1f);
piss.Effects[0].Data!.Duration = 5;
foreach (var r in new IMajorRecordGetter[] { pissPoison, piss })
    Console.WriteLine($"  {r.FormKey.ID:X3} {r.EditorID}");

// ---- Pocket ----
//
// Fixed ids the SKSE plugin looks up (skse/src/pocket/Pocket.cpp): 0x906 + the protocol's kPocket*
// kind. MSC's beer, empty bottles, food and cigarettes as plain misc items in Skyrim's inventory, so
// nothing can be eaten or drunk on Skyrim's side; they come out into MSC's hand. Each looks like the
// vanilla item named (model, bounds and sounds copied).
(IModelGetter? Model, IObjectBoundsGetter? Bounds, FormKey? Up, FormKey? Down) Look(string editorId)
{
    var food = skyrim.Ingestibles.FirstOrDefault(r => r.EditorID == editorId);
    if (food != null) return (food.Model, food.ObjectBounds, food.PickUpSound.FormKeyNullable, food.PutDownSound.FormKeyNullable);
    var misc = skyrim.MiscItems.FirstOrDefault(r => r.EditorID == editorId)
        ?? throw new InvalidOperationException($"{editorId} not in Skyrim.esm as food or misc item");
    return (misc.Model, misc.ObjectBounds, misc.PickUpSound.FormKeyNullable, misc.PutDownSound.FormKeyNullable);
}
var pocket = new (string EditorId, string Name, string LooksLike, float Weight, uint Value)[]
{
    ("PerkeleRimBeer", "MSC Beer", "Ale", 0.5f, 3),
    ("PerkeleRimEmptyBottle", "Empty Bottle", "WineBottle01AEmpty", 0.3f, 0),
    ("PerkeleRimSausages", "Sausages", "FoodBeefCooked", 0.8f, 4),
    ("PerkeleRimPizza", "Pizza", "FoodPie", 0.5f, 5),
    ("PerkeleRimPotatoChips", "Potato Chips", "FoodPotatoesBaked", 0.3f, 2),
    ("PerkeleRimMacaronBox", "Macaron Box", "FoodSweetroll", 0.5f, 3),
    ("PerkeleRimCigarette", "Cigarette", "Quill01", 0f, 1),
};
for (uint i = 0; i < pocket.Length; i++)
{
    var p = pocket[i];
    var look = Look(p.LooksLike);
    var item = new MiscItem(new FormKey(mod.ModKey, 0x906 + i), SkyrimRelease.SkyrimSE)
    {
        EditorID = p.EditorId,
        Name = p.Name,
        Model = look.Model?.DeepCopy(),
        ObjectBounds = look.Bounds?.DeepCopy() ?? new ObjectBounds(),
        Weight = p.Weight,
        Value = p.Value,
    };
    if (look.Up != null) item.PickUpSound.SetTo(look.Up.Value);
    if (look.Down != null) item.PutDownSound.SetTo(look.Down.Value);
    mod.MiscItems.Add(item);
    Console.WriteLine($"  {item.FormKey.ID:X3} {item.EditorID} (looks like {p.LooksLike})");
}
mod.ModHeader.Stats.NextFormID = 0x90F;  // after the pocket (0x906 + 7) and piss (0x90D, 0x90E)

Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(output))!);
mod.WriteToBinary(output);
Console.WriteLine($"wrote {output}");
return 0;
